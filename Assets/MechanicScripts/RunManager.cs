using UnityEngine;
using System.IO;

/// <summary>
/// Oyunlar arasi kalici verileri JSON dosyasinda saklayan yonetici.
/// Otomatik olarak olusturulur, sahneye eklemenize gerek yok.
/// </summary>
public class RunManager : MonoBehaviour
{
    public static RunManager Instance { get; private set; }

    public RunData currentData;
    private string saveFilePath;

    [RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.BeforeSceneLoad)]
    static void AutoCreate()
    {
        if (Instance == null)
        {
            GameObject go = new GameObject("RunManager (AutoGenerated)");
            RunManager rm = go.AddComponent<RunManager>();
            DontDestroyOnLoad(go);

            rm.saveFilePath = Application.persistentDataPath + "/rundata.json";
            rm.LoadData();
            Instance = rm;
        }
    }

    private void Awake()
    {
        if (Instance != null && Instance != this)
        {
            Destroy(gameObject);
            return;
        }
        Instance = this;
    }

    public void LoadData()
    {
        if (File.Exists(saveFilePath))
        {
            string json = File.ReadAllText(saveFilePath);
            currentData = JsonUtility.FromJson<RunData>(json);
        }
        else
        {
            currentData = new RunData();
        }
    }

    public void SaveData()
    {
        string json = JsonUtility.ToJson(currentData, true);
        File.WriteAllText(saveFilePath, json);
    }

    public void AddZombieKill()
    {
        currentData.totalZombieKills++;
        SaveData();
    }

    public void AddDeath(string reason)
    {
        if (reason == "Saglik" || reason == "Sağlık")
        {
            currentData.deathByHealth++;
        }
        else if (reason == "Aclik" || reason == "Açlık")
        {
            currentData.deathByHunger++;
        }
        else if (reason == "Susuzluk")
        {
            currentData.deathByThirst++;
        }

        SaveData();
    }

    public void CheckAndSaveWinTime(float timeInSeconds)
    {
        if (currentData.fastestWinTime == 0f || timeInSeconds < currentData.fastestWinTime)
        {
            currentData.fastestWinTime = timeInSeconds;
            SaveData();
        }
    }
}